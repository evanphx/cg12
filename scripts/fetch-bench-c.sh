#!/usr/bin/env bash
#
# fetch-bench-c.sh — fetch the real C programs the compiler is measured against.
#
# WHY THIS IS NOT VENDORED
#
# The in-tree C corpus is 54 files, none over 2 KB, which is fine for testing
# what the front end accepts and useless for measuring what the compiler costs:
# nothing in it exercises pass memory, the register allocator's interference
# graph, or any of the quadratics. The measurements need real programs, and real
# programs are megabytes. SQLite's amalgamation alone is 9.2 MB of generated C —
# larger than the rest of the repository put together — so it is fetched by
# pinned hash instead of committed, and the tools that use it (cmd/ccstat,
# scripts/cc-identity-check.sh) skip cleanly when it is absent.
#
# WHAT IS HERE, AND WHY EACH ONE
#
#   sqlite  260k lines, public domain, one translation unit. The day-to-day
#           workload: it compiles clean at -O0 and -O today, in about four
#           seconds, which is the whole point — a measurement loop nobody
#           minds running.
#
#   quickjs 90k lines, MIT. The third interpreter, and the one several of the
#           optimizer's heuristics were tuned for: its JS_CallInternal dispatches
#           on a computed goto, where SQLite's VDBE and Lua's interpreter both
#           dispatch on a switch. It cannot be built as one translation unit --
#           libregexp.c and quickjs.c each define a static is_digit and a static
#           compute_stack_size, with different signatures, which gcc rejects too
#           -- so the support files are built separately and only quickjs.c goes
#           through the compiler under test. That is also where the interpreter
#           is, so it is the part worth measuring.
#
#   lua     25k lines, MIT, compiled as a single translation unit. Smaller and
#           slower to reach, but it is the one whose output can be *run*, so it
#           is the workload that can prove an optimization did not change
#           behaviour rather than only bytes. Note that lvm.c does not survive
#           -O today (a nil live-out set for an unreachable block, in
#           lower.buildPhiInterference); at -O0 the whole thing builds and runs.
#
# USAGE
#
#   scripts/fetch-bench-c.sh            # fetch everything missing
#   scripts/fetch-bench-c.sh sqlite     # just the one
#   BENCH_C_DIR=/somewhere scripts/fetch-bench-c.sh
#
set -euo pipefail

cd "$(dirname "$0")/.."
ROOT=$(pwd)

BENCH_C_DIR=${BENCH_C_DIR:-$ROOT/cc/testdata/bench}

SQLITE_URL=https://www.sqlite.org/2024/sqlite-amalgamation-3470000.zip
SQLITE_SHA=2842fddbb1cc33f66c7da998a57535f14a6bfee159676a07bb4bf3e59375d93e

LUA_URL=https://www.lua.org/ftp/lua-5.4.7.tar.gz
LUA_SHA=9fbf5e28ef86c69858f6d3d34eccc32e911c1a28b4120ff3e84aaa70cfbf1e30

QUICKJS_URL=https://bellard.org/quickjs/quickjs-2024-01-13.tar.xz
QUICKJS_SHA=3c4bf8f895bfa54beb486c8d1218112771ecfc5ac3be1036851ef41568212e03

note() { echo "[fetch-bench-c] $*" >&2; }
fail() { echo "[fetch-bench-c] $*" >&2; exit 1; }

# verify checks a downloaded file against its pinned digest. A mismatch is fatal
# and leaves nothing behind: a benchmark input that is not the input the numbers
# were recorded against is worse than no input at all.
verify() {
	local path=$1 want=$2
	local got
	got=$(sha256sum "$path" | cut -d' ' -f1)
	if [ "$got" != "$want" ]; then
		rm -f "$path"
		fail "$path: sha256 $got, expected $want"
	fi
}

fetch_sqlite() {
	local target="$BENCH_C_DIR/sqlite3.c"
	if [ -f "$target" ]; then
		note "sqlite already present: $target"
		return
	fi
	local work
	work=$(mktemp -d)
	trap 'rm -rf "$work"' RETURN
	note "fetching sqlite amalgamation"
	curl -fsSL -o "$work/sqlite.zip" "$SQLITE_URL"
	verify "$work/sqlite.zip" "$SQLITE_SHA"
	unzip -q -d "$work" "$work/sqlite.zip"
	mkdir -p "$BENCH_C_DIR"
	cp "$work"/sqlite-amalgamation-*/sqlite3.c "$target"
	cp "$work"/sqlite-amalgamation-*/sqlite3.h "$BENCH_C_DIR/sqlite3.h"
	note "wrote $target ($(wc -l <"$target") lines)"
}

# fetch_lua also writes the single-translation-unit wrapper. Lua ships as 33
# separate .c files, and cg12 cannot link 33 objects together yet -- every object
# defines __cg12_stackmaps, so the host linker rejects the duplicate. Compiling
# the lot as one unit sidesteps that, and is also the shape the measurement wants:
# one compiler invocation, one module, whole-program inlining in play.
fetch_lua() {
	local dir="$BENCH_C_DIR/lua"
	if [ -f "$dir/onelua.c" ]; then
		note "lua already present: $dir/onelua.c"
		return
	fi
	local work
	work=$(mktemp -d)
	trap 'rm -rf "$work"' RETURN
	note "fetching lua"
	curl -fsSL -o "$work/lua.tar.gz" "$LUA_URL"
	verify "$work/lua.tar.gz" "$LUA_SHA"
	tar -xzf "$work/lua.tar.gz" -C "$work"
	mkdir -p "$dir"
	cp "$work"/lua-*/src/*.c "$work"/lua-*/src/*.h "$dir/"
	# The core, then the standard library, then linit.c, which registers it.
	# lua.c (the interpreter's main) is left out so the unit is the library;
	# add it to build a runnable binary.
	{
		echo "// Generated by scripts/fetch-bench-c.sh. Lua as one translation unit."
		echo "// See the note in that script about __cg12_stackmaps."
		for unit in lapi lcode lctype ldebug ldo ldump lfunc lgc llex lmem lobject \
			lopcodes lparser lstate lstring ltable ltm lundump lvm lzio \
			lauxlib lbaselib lcorolib ldblib liolib lmathlib loadlib loslib \
			lstrlib ltablib lutf8lib linit; do
			echo "#include \"$unit.c\""
		done
	} >"$dir/onelua.c"
	note "wrote $dir/onelua.c"
}

# fetch_quickjs unpacks the sources as they ship. Unlike lua there is no
# one-translation-unit wrapper: quickjs.c and libregexp.c collide on two static
# names, so whoever builds this compiles the support files separately and hands
# only quickjs.c to the compiler under test.
fetch_quickjs() {
	local dir="$BENCH_C_DIR/quickjs"
	if [ -f "$dir/quickjs.c" ]; then
		note "quickjs already present: $dir/quickjs.c"
		return
	fi
	local work
	work=$(mktemp -d)
	trap 'rm -rf "$work"' RETURN
	note "fetching quickjs"
	curl -fsSL -o "$work/quickjs.tar.xz" "$QUICKJS_URL"
	verify "$work/quickjs.tar.xz" "$QUICKJS_SHA"
	tar -xJf "$work/quickjs.tar.xz" -C "$work"
	mkdir -p "$dir"
	cp "$work"/quickjs-*/*.c "$work"/quickjs-*/*.h "$work"/quickjs-*/VERSION "$dir/"
	note "wrote $dir/quickjs.c ($(wc -l <"$dir/quickjs.c") lines)"
}

targets=("$@")
if [ ${#targets[@]} -eq 0 ]; then
	targets=(sqlite lua quickjs)
fi
for target in "${targets[@]}"; do
	case "$target" in
	sqlite) fetch_sqlite ;;
	lua) fetch_lua ;;
	quickjs) fetch_quickjs ;;
	*) fail "unknown target $target (want sqlite, lua or quickjs)" ;;
	esac
done
